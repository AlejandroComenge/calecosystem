function cartDomain(): string {
  return [
    '/**',
    ' * Reglas del carrito, en el dominio y sin dependencias.',
    ' *',
    ' * Estan aqui y no en la ruta HTTP porque son las reglas que mas veces se',
    ' * tocan y las que mas caro sale equivocar: un redondeo mal hecho es dinero.',
    ' */',
    '',
    'export interface CartLineInput {',
    '  productId: string;',
    '  quantity: number;',
    '}',
    '',
    'export interface PricedLine {',
    '  productId: string;',
    '  quantity: number;',
    '  unitPrice: number;',
    '  lineTotal: number;',
    '}',
    '',
    'export interface CartTotals {',
    '  subtotal: number;',
    '  tax: number;',
    '  total: number;',
    '}',
    '',
    'export const DEFAULT_TAX_RATE = 0.21;',
    '',
    '/** Redondeo a centimos. Sin esto, 0.1 + 0.2 acaba en la factura. */',
    'export function roundCents(value: number): number {',
    '  return Math.round(value * 100) / 100;',
    '}',
    '',
    'export function priceLines(',
    '  lines: readonly CartLineInput[],',
    '  priceOf: (productId: string) => number | undefined,',
    '): PricedLine[] {',
    '  return lines.map((line) => {',
    '    const unitPrice = priceOf(line.productId);',
    '    if (unitPrice === undefined) {',
    "      throw new Error('Producto no encontrado: ' + line.productId);",
    '    }',
    '    if (!Number.isInteger(line.quantity) || line.quantity <= 0) {',
    "      throw new Error('Cantidad no valida para ' + line.productId);",
    '    }',
    '    return {',
    '      productId: line.productId,',
    '      quantity: line.quantity,',
    '      unitPrice,',
    '      lineTotal: roundCents(unitPrice * line.quantity),',
    '    };',
    '  });',
    '}',
    '',
    'export function calculateTotals(',
    '  lines: readonly PricedLine[],',
    '  taxRate: number = DEFAULT_TAX_RATE,',
    '): CartTotals {',
    '  const subtotal = roundCents(lines.reduce((sum, line) => sum + line.lineTotal, 0));',
    '  const tax = roundCents(subtotal * taxRate);',
    '  return { subtotal, tax, total: roundCents(subtotal + tax) };',
    '}',
  ].join('\n');
}

function cartDomainTest(): string {
  return [
    "import test from 'node:test';",
    "import assert from 'node:assert/strict';",
    "import { calculateTotals, priceLines, roundCents } from './CartPricing.ts';",
    '',
    "const prices: Record<string, number> = { 'p-1': 19.99, 'p-2': 5.5 };",
    'const priceOf = (id: string) => prices[id];',
    '',
    "test('calcula el total de cada linea', () => {",
    "  const lines = priceLines([{ productId: 'p-1', quantity: 3 }], priceOf);",
    '  assert.equal(lines[0]?.lineTotal, 59.97);',
    '});',
    '',
    "test('rechaza cantidades no validas', () => {",
    "  assert.throws(() => priceLines([{ productId: 'p-1', quantity: 0 }], priceOf), /Cantidad/);",
    "  assert.throws(() => priceLines([{ productId: 'p-1', quantity: 1.5 }], priceOf), /Cantidad/);",
    '});',
    '',
    "test('rechaza productos inexistentes', () => {",
    "  assert.throws(() => priceLines([{ productId: 'nope', quantity: 1 }], priceOf), /no encontrado/);",
    '});',
    '',
    "test('aplica impuestos sobre el subtotal redondeado', () => {",
    '  const lines = priceLines(',
    "    [{ productId: 'p-1', quantity: 1 }, { productId: 'p-2', quantity: 2 }],",
    '    priceOf,',
    '  );',
    '  const totals = calculateTotals(lines);',
    '  assert.equal(totals.subtotal, 30.99);',
    '  assert.equal(totals.tax, 6.51);',
    '  assert.equal(totals.total, 37.5);',
    '});',
    '',
    "test('el redondeo evita los errores de coma flotante', () => {",
    '  assert.equal(roundCents(0.1 + 0.2), 0.3);',
    '});',
  ].join('\n');
}

