const TOOL = 'calec.template.ecommerce';
const file = fileFactory(TOOL);

/**
 * Plantilla de comercio electronico.
 *
 * Aporta lo que ninguna tienda puede no tener y que un CRUD generico nunca
 * deduce: carrito con persistencia local, proceso de compra y panel de
 * pedidos. El catalogo si sale del analisis, porque los productos varian de
 * un negocio a otro y la plantilla no debe imponer su modelo.
 */
export const ecommerceTemplate: ProjectTemplate = {
  id: 'calec.template.ecommerce',
  name: 'E-commerce',
  description: 'Catalogo, carrito, proceso de compra y panel de pedidos.',
  kind: 'ecommerce',
  tier: 'community',
  frameworks: ['react'],

  detect(requirements: RequirementsModel): TemplateMatch {
    return scoreTemplate(requirements, {
      signals: [
        'tienda', 'ecommerce', 'e-commerce', 'comercio electronico', 'carrito',
        'checkout', 'marketplace', 'catalogo', 'vender', 'venta', 'compra',
        'comprar', 'pedidos', 'envio', 'stock',
      ],
      entities: ['Product', 'Order', 'Cart', 'Customer'],
      features: ['payments'],
      // Un panel interno gestiona pedidos y productos, pero no es una tienda:
      // generarle un carrito y un proceso de compra es ruido, no valor.
      antiSignals: [
        'landing', 'captacion de leads', 'panel interno', 'uso interno',
        'empleados', 'backoffice', 'back office', 'herramienta interna',
      ],
    });
  },

  refine(blueprint: Blueprint): Blueprint {
    let refined = ensureEntity(blueprint, 'Product');
    refined = ensureEntity(refined, 'Order');
    refined = ensureEntity(refined, 'Customer');
    refined = ensureEntity(refined, 'CartItem', [
      { name: 'id', type: 'uuid', required: true },
      { name: 'productId', type: 'reference', required: true, references: 'Product' },
      { name: 'quantity', type: 'number', required: true },
      { name: 'unitPrice', type: 'decimal', required: true },
      { name: 'createdAt', type: 'datetime', required: true },
      { name: 'updatedAt', type: 'datetime', required: true },
    ]);

    refined = addPages(refined, [
      { route: '/catalog', name: 'Catalog', kind: 'list', entity: 'Product', requiresAuth: false },
      { route: '/cart', name: 'Cart', kind: 'detail', entity: 'CartItem', requiresAuth: false },
      { route: '/checkout', name: 'Checkout', kind: 'form', entity: 'Order', requiresAuth: false },
      { route: '/admin/orders', name: 'AdminOrders', kind: 'dashboard', entity: 'Order', requiresAuth: true },
      { route: '/admin/products', name: 'AdminProducts', kind: 'dashboard', entity: 'Product', requiresAuth: true },
    ]);

    refined = addEndpoints(refined, [
      {
        method: 'POST',
        path: '/api/checkout',
        summary: 'Confirma el carrito y crea el pedido',
        entity: 'Order',
        requiresAuth: false,
      },
      {
        method: 'GET',
        path: '/api/catalog',
        summary: 'Catalogo publico con filtros y paginacion',
        entity: 'Product',
        requiresAuth: false,
      },
    ]);

    // El inventario es la fuente numero uno de incidencias en una tienda:
    // dos clientes comprando la ultima unidad a la vez.
    refined = {
      ...refined,
      risks: [
        ...refined.risks,
        {
          id: 'RISK-STOCK-RACE',
          title: 'Condicion de carrera al descontar stock',
          impact: 'high',
          mitigation:
            'Descontar existencias dentro de la misma transaccion que crea el pedido, con bloqueo por fila.',
          owner: 'tester',
        },
      ],
    };

    return recordTemplateDecision(refined, 'E-commerce', 'carrito, proceso de compra y panel de pedidos');
  },

  scaffold({ blueprint, dependencies }: ScaffoldContext): VirtualFile[] {
    const root = 'apps/web/src';

    dependencies.contribute({
      workspace: 'web',
      requestedBy: TOOL,
      scripts: { 'test:e2e': 'echo "Anade aqui tu runner de e2e"' },
    });

    return [
      file(`${root}/features/cart/CartContext.tsx`, cartContext(blueprint.slug)),
      file(`${root}/features/cart/useCart.ts`, useCartHook()),
      file(`${root}/features/catalog/ProductGrid.tsx`, productGrid()),
      file(`${root}/pages/CatalogPage.tsx`, catalogPage()),
      file(`${root}/pages/CartPage.tsx`, cartPage()),
      file(`${root}/pages/CheckoutPage.tsx`, checkoutPage()),
      file(`${root}/pages/AdminOrdersPage.tsx`, adminOrdersPage()),
      file('apps/api/src/routes/checkout.routes.ts', checkoutRoutes()),
      file('apps/api/src/application/CheckoutService.ts', checkoutService()),
      // Nombre deliberado: son las reglas de precio del carrito, no la
      // entidad `Cart` que el analizador ya pudo deducir del enunciado.
      file('apps/api/src/domain/CartPricing.ts', cartDomain()),
      file('apps/api/src/domain/CartPricing.test.ts', cartDomainTest()),
    ];
  },
};

function cartContext(slug: string): string {
  return [
    '/**',
    ' * Estado del carrito.',
    ' *',
    ' * Se guarda en `localStorage` porque un carrito que se vacia al recargar',
    ' * pierde ventas. El precio se recalcula SIEMPRE en el servidor al pagar:',
    ' * lo que hay aqui es una copia de conveniencia para pintar la interfaz.',
    ' */',
    "import { createContext, useCallback, useEffect, useMemo, useState, type ReactNode } from 'react';",
    "import type { Product } from '../../types.ts';",
    '',
    'export interface CartLine {',
    '  productId: string;',
    '  name: string;',
    '  unitPrice: number;',
    '  quantity: number;',
    '}',
    '',
    'export interface CartState {',
    '  lines: CartLine[];',
    '  add(product: Product, quantity?: number): void;',
    '  remove(productId: string): void;',
    '  setQuantity(productId: string, quantity: number): void;',
    '  clear(): void;',
    '  itemCount: number;',
    '  subtotal: number;',
    '}',
    '',
    'export const CartContext = createContext<CartState | null>(null);',
    '',
    `const STORAGE_KEY = '${slug}.cart';`,
    '',
    'function readStoredLines(): CartLine[] {',
    '  try {',
    '    const raw = localStorage.getItem(STORAGE_KEY);',
    '    return raw ? (JSON.parse(raw) as CartLine[]) : [];',
    '  } catch {',
    '    // Almacenamiento no disponible o corrupto: arrancar vacio es',
    '    // preferible a romper la aplicacion entera.',
    '    return [];',
    '  }',
    '}',
    '',
    'export function CartProvider({ children }: { children: ReactNode }) {',
    '  const [lines, setLines] = useState<CartLine[]>(readStoredLines);',
    '',
    '  useEffect(() => {',
    '    try {',
    '      localStorage.setItem(STORAGE_KEY, JSON.stringify(lines));',
    '    } catch {',
    '      // Modo privado o cuota agotada: no es motivo para perder el carrito',
    '      // de esta sesion.',
    '    }',
    '  }, [lines]);',
    '',
    '  const add = useCallback((product: Product, quantity = 1) => {',
    '    setLines((current) => {',
    '      const existing = current.find((line) => line.productId === product.id);',
    '      if (existing) {',
    '        return current.map((line) =>',
    '          line.productId === product.id',
    '            ? { ...line, quantity: line.quantity + quantity }',
    '            : line,',
    '        );',
    '      }',
    '      return [',
    '        ...current,',
    '        {',
    '          productId: product.id,',
    '          name: product.name,',
    '          unitPrice: Number(product.price),',
    '          quantity,',
    '        },',
    '      ];',
    '    });',
    '  }, []);',
    '',
    '  const remove = useCallback((productId: string) => {',
    '    setLines((current) => current.filter((line) => line.productId !== productId));',
    '  }, []);',
    '',
    '  const setQuantity = useCallback((productId: string, quantity: number) => {',
    '    // Cantidad cero equivale a eliminar: evita lineas fantasma en el carrito.',
    '    if (quantity <= 0) {',
    '      setLines((current) => current.filter((line) => line.productId !== productId));',
    '      return;',
    '    }',
    '    setLines((current) =>',
    '      current.map((line) => (line.productId === productId ? { ...line, quantity } : line)),',
    '    );',
    '  }, []);',
    '',
    '  const clear = useCallback(() => setLines([]), []);',
    '',
    '  const value = useMemo<CartState>(() => {',
    '    const itemCount = lines.reduce((total, line) => total + line.quantity, 0);',
    '    const subtotal = lines.reduce((total, line) => total + line.unitPrice * line.quantity, 0);',
    '    return { lines, add, remove, setQuantity, clear, itemCount, subtotal };',
    '  }, [lines, add, remove, setQuantity, clear]);',
    '',
    '  return <CartContext.Provider value={value}>{children}</CartContext.Provider>;',
    '}',
  ].join('\n');
}

function useCartHook(): string {
  return [
    "import { useContext } from 'react';",
    "import { CartContext, type CartState } from './CartContext.tsx';",
    '',
    '/** Acceso al carrito. Falla pronto si falta el proveedor. */',
    'export function useCart(): CartState {',
    '  const context = useContext(CartContext);',
    '  if (!context) {',
    "    throw new Error('useCart debe usarse dentro de <CartProvider>.');",
    '  }',
    '  return context;',
    '}',
  ].join('\n');
}

